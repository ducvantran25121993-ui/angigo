import fs from 'fs';
import path from 'path';
import { CURATED_RECIPES } from '../src/data/recipes';

const outDir = path.resolve(process.cwd(), 'public', 'recipes');
fs.mkdirSync(outDir, { recursive: true });

// Clean old json files that no longer exist in CURATED_RECIPES
const existingFiles = fs.readdirSync(outDir).filter((f) => f.endsWith('.json'));
const validKeys = new Set(Object.keys(CURATED_RECIPES));
for (const file of existingFiles) {
  const key = file.replace(/\.json$/, '');
  if (!validKeys.has(key)) {
    fs.unlinkSync(path.join(outDir, file));
  }
}

const metaMap: Record<string, { cookTime: string; difficulty: string; seoTitle?: string }> = {};
let totalBytes = 0;

for (const [id, recipe] of Object.entries(CURATED_RECIPES)) {
  const normalizedRecipe = {
    ...recipe,
    steps: recipe.steps || (recipe as any).instructions || [],
  };
  const json = JSON.stringify(normalizedRecipe);
  fs.writeFileSync(path.join(outDir, `${id}.json`), json, 'utf-8');
  totalBytes += Buffer.byteLength(json, 'utf-8');

  metaMap[id] = {
    cookTime: recipe.cookTime || '25 phút',
    difficulty: recipe.difficulty || 'Dễ',
    ...(recipe.seoTitle ? { seoTitle: recipe.seoTitle } : {}),
  };
}

const metaFileContent = `// Auto-generated by scripts/split-recipes.ts — do not edit manually
import { RECIPE_SLUG_ALIASES } from './recipeSlugs';

export interface RecipeCardMeta {
  cookTime: string;
  difficulty: string;
  seoTitle?: string;
}

export const CURATED_RECIPE_META: Record<string, RecipeCardMeta> = ${JSON.stringify(metaMap, null, 2)};

export function resolveCuratedRecipeKey(dishId: string): string | null {
  if (!dishId) return null;
  if (CURATED_RECIPE_META[dishId]) return dishId;
  const directAlias = RECIPE_SLUG_ALIASES[dishId];
  if (directAlias && CURATED_RECIPE_META[directAlias]) return directAlias;
  const reverseAlias = Object.keys(RECIPE_SLUG_ALIASES).find(
    (k) => RECIPE_SLUG_ALIASES[k] === dishId && CURATED_RECIPE_META[k]
  );
  return reverseAlias || null;
}
`;

fs.writeFileSync(path.resolve(process.cwd(), 'src', 'data', 'recipeMeta.ts'), metaFileContent, 'utf-8');

console.log(
  `Split ${validKeys.size} curated recipes into public/recipes/*.json (${(totalBytes / 1024).toFixed(1)} KB total, avg ${(totalBytes / validKeys.size / 1024).toFixed(1)} KB/recipe) and generated src/data/recipeMeta.ts.`
);
